'use strict';

const {js} = require('./utils');

module.exports = function migrationHistorySource(spec) {
  return [
    "'use strict';", '',
    "const fs = require('node:fs');",
    "const path = require('node:path');",
    "const crypto = require('node:crypto');",
    'const schemaPath = path.resolve(__dirname, "..", ' + js(spec.database.prisma.schemaPath) + ');',
    'const dir = path.join(path.dirname(schemaPath), "migrations");',
    'const manifestPath = path.join(path.dirname(schemaPath), "migration-history.json");',
    'function checksum(value) {return crypto.createHash("sha256").update(value).digest("hex");}',
    'function entries() {',
    '  if (!fs.existsSync(dir)) throw new Error("Migration directory is absent: run db:migrate:init");',
    '  const folders = fs.readdirSync(dir, {withFileTypes:true}).filter(item => item.isDirectory()).map(item => item.name).sort();',
    '  const migrations = {};',
    '  for (const name of folders) {',
    '    if (!/^\\d{14}_[a-zA-Z0-9_-]+$/.test(name)) throw new Error("Unexpected migration directory: " + name);',
    '    const sql = path.join(dir,name,"migration.sql");',
    '    if (!fs.existsSync(sql) || !fs.statSync(sql).isFile()) throw new Error("Missing migration.sql: " + name);',
    '    migrations[name] = checksum(fs.readFileSync(sql));',
    '  }',
    '  if (!folders.length) throw new Error("No SQL migration files found");',
    '  const lock = path.join(dir,"migration_lock.toml");',
    '  if (!fs.existsSync(lock) || !/provider\\s*=\\s*"postgresql"/.test(fs.readFileSync(lock,"utf8")))',
    '    throw new Error("Prisma migration_lock.toml is absent or not PostgreSQL");',
    '  // Prisma may rewrite lock comments/whitespace during migrate dev; enforce provider semantics.',
    '  return {migrations, lockSha256:checksum("postgresql")};',
    '}',
    'function verify({record=false, allowNew=false}={}) {',
    '  const actual=entries();',
    '  const manifest=fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath,"utf8")) : null;',
    '  if (!manifest && !record) throw new Error("Migration history manifest missing; run db:migrate:record after reviewing SQL");',
    '  if (manifest) {',
    '    if (manifest.version!==1 || !manifest.migrations || !manifest.lockSha256)',
    '      throw new Error("Invalid migration history manifest");',
    '    if (manifest.lockSha256!==actual.lockSha256) throw new Error("Migration lock changed; history is immutable");',
    '    for (const [name,digest] of Object.entries(manifest.migrations)) {',
    '      if (actual.migrations[name]!==digest) throw new Error("Applied or reviewed migration changed: " + name);',
    '    }',
    '    const newNames=Object.keys(actual.migrations).filter(name=>!(name in manifest.migrations));',
    '    if (newNames.length && !record && !allowNew) throw new Error("Untracked SQL migrations: " + newNames.join(", ") + "; review and run db:migrate:record");',
    '  }',
    '  if (record) {',
    '    const next={version:1,lockSha256:actual.lockSha256,migrations:actual.migrations};',
    '    const tmp=manifestPath+".tmp-"+process.pid;',
    '    try {fs.writeFileSync(tmp,JSON.stringify(next,null,2)+"\\n",{flag:"wx"});fs.renameSync(tmp,manifestPath);}',
    '    finally {if(fs.existsSync(tmp))fs.unlinkSync(tmp);}',
    '  }',
    '  return true;',
    '}',
    'if(require.main===module) {',
    '  try {verify({record:process.argv.includes("--record"),allowNew:process.argv.includes("--allow-new")});',
    '    console.log("Prisma migration history verified");}',
    '  catch(error) {console.error(error.message);process.exitCode=1;}',
    '}',
    'module.exports={verify,entries};',''
  ].join('\n');
};
